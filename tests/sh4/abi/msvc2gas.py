#!/usr/bin/env python3
"""Turn the Microsoft SH-4 compiler listings of msvc-sh4-abi-reference.txt
back into GNU as source, instruction for instruction.

The listing shows PC-relative operands as absolute offsets ("mov.l 0x18,r3")
and literal pool words as ".byte" pairs with a relocation table.  Offsets
become local labels, relocated words become ".long SYMBOL", and every other
".byte" pair is kept as is.  The output therefore assembles to the same
instructions as the reference object, with the same layout.

    msvc2gas.py REFERENCE.txt OUT.s [FUNCTION...]
"""

import ast
import re
import sys

PCREL = re.compile(r'^(mov\.l|mov\.w|mova|bra|bsr|bt|bf|bt/s|bf/s)\s+(0x[0-9a-f]+)(,.*)?$')


def parse(path):
    funcs = {}
    order = []
    cur = None
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('== '):
            cur = line[3:].strip()
            funcs[cur] = {'insns': [], 'relocs': {}}
            order.append(cur)
        elif cur and line.startswith('relocs:'):
            relocs = ast.literal_eval(line[len('relocs:'):].strip())
            funcs[cur]['relocs'] = {int(k, 16): v for k, v in relocs.items()}
            cur = None
        elif cur and re.match(r'^\s+[0-9a-f]{4} ', line):
            off, text = line.split(None, 1)
            funcs[cur]['insns'].append((int(off, 16), ' '.join(text.split())))
    return order, funcs


def label(func, off):
    return 'L%s_%04x' % (func.lstrip('_'), off)


def symbol(name, strings):
    # MSVC string literal symbols become local labels.
    if name.startswith('??_C@'):
        return strings.setdefault(name, 'Lstr%d' % len(strings))
    return name


def convert(func, body, strings, out):
    relocs = body['relocs']
    out.append('\t.text')
    out.append('\t.align\t2')
    out.append('\t.global\t%s' % func)
    out.append('%s:' % func)
    skip = set()
    for off, text in body['insns']:
        if off in skip:
            continue
        out.append('%s:' % label(func, off))
        if off in relocs:
            if not text.startswith('.byte'):
                raise SystemExit('%s+%#x: relocation on an instruction' % (func, off))
            out.append('\t.long\t%s' % symbol(relocs[off], strings))
            skip.add(off + 2)
            continue
        m = PCREL.match(text)
        if m:
            text = '%s\t%s%s' % (m.group(1), label(func, int(m.group(2), 16)),
                                 m.group(3) or '')
        elif ' ' in text:
            op, rest = text.split(' ', 1)
            text = '%s\t%s' % (op, rest)
        out.append('\t' + text)


def main():
    ref, outpath = sys.argv[1], sys.argv[2]
    wanted = sys.argv[3:]
    order, funcs = parse(ref)
    strings = {}
    out = ['! Generated by msvc2gas.py from %s; do not edit.' % ref.split('/')[-1],
           '\t.little']
    for f in order:
        if wanted and f not in wanted:
            continue
        convert(f, funcs[f], strings, out)
    if strings:
        out.append('\t.data')
        for name, lab in strings.items():
            # ??_C@_01FNLH@a?$AA@ is the literal "a".
            m = re.match(r'^\?\?_C@_0\w\w+@(.*?)\?\$AA@$', name)
            if not m:
                raise SystemExit('cannot decode string symbol ' + name)
            out.append('%s:\t.asciz\t"%s"' % (lab, m.group(1)))
    open(outpath, 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
